using System;
using System.Data;
using CORNCommon.Classes;
using CORNDataAccessLayer.Classes;


namespace CORNDatabaseLayer.Classes
{
	public class spInsertBRAND_ASSIGNMENTClient
	{
		#region Private Members
		private string sp_Name = " spInsertBRAND_ASSIGNMENTClient" ;
		private IDbConnection m_connection;
		private IDbTransaction m_transaction;
        
		private int m_USER_ID;
		private int m_PRINCIPAL_ID;
        private DateTime m_LASTUPDATE_DATE;
        private bool m_Is_ManualDiscount;
		#endregion
        
		#region Public Properties
		public int USER_ID
		{
			set
			{
				m_USER_ID = value ;
			}
			get
			{
				return m_USER_ID;
			}
		}
        
		public int PRINCIPAL_ID
		{
			set
			{
				m_PRINCIPAL_ID = value ;
			}
			get
			{
				return m_PRINCIPAL_ID;
			}
		}

        public DateTime LASTUPDATE_DATE
        {
            set
            {
                m_LASTUPDATE_DATE = value;
            }
            get
            {
                return m_LASTUPDATE_DATE;
            }
        }

        public bool Is_ManualDiscount
        {
            set { m_Is_ManualDiscount = value; }
            get { return m_Is_ManualDiscount; }
        }

		public IDbConnection  Connection
		{
			set
			{
				m_connection = value;
			}
			get
			{
				return m_connection;
			}
		}
		public IDbTransaction  Transaction
		{
			set
			{
				m_transaction = value;
			}
			get
			{
				return m_transaction;
